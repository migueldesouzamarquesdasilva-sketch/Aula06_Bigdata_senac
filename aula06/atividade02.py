# digitar um valor e tem q aparecer o dobor, triplo e quadrado do número
#

#---------------------------

#Esrutura de Repetição
#Laço For
for i in range(3):
    print(f'\nRODADA {i + 1}')
    num = float(input('Número: '))

    dobro = num * 2
    triplo = num * 3
    quadrado = num ** 2

    print(f'O dobro do número é: {dobro}')
    print(f'O triplo do número é: {triplo}')
    print(f'O o quadrado do número é: {quadrado}')
    










